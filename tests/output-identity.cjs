const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../org.liby0zud.customimage/contents/ui/PreviewGeometry.js'), 'utf8'), ctx);
const a = {name:'HDMI-A-1', width:2560, height:1440};
const b = {name:'eDP-1', width:1280, height:800};
assert.equal(ctx.findOutput([a,b], a.name), a);
assert.equal(ctx.findOutput([b,a], a.name), a);
assert.equal(ctx.findOutput([b], a.name), null);
assert.equal(ctx.findOutput([b], b.name), b);
assert.equal(ctx.findOutput([a,b], ''), null);
assert.equal(ctx.findOutput([], b.name), null);
assert.equal(ctx.findOutput([b,a], b.name), b);
assert.equal(ctx.matchesOutput(a.name, b.name), false);
assert.equal(ctx.matchesOutput(b.name, b.name), true);
assert.equal(ctx.matchesOutput(a.name, ''), false);
assert.equal(ctx.matchesOutput('', b.name), true);
assert.equal(ctx.resolve(null,null,null,ctx.findOutput([b],a.name)).source, 'placeholder');
console.log('Passed: output names survive reorder/removal/reconnection; disconnected A does not resolve to B; foreign profile guard.');
